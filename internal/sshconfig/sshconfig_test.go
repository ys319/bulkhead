package sshconfig

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func read(t *testing.T, path string) string {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(data)
}

func TestFragment(t *testing.T) {
	got := Fragment("/cfg/id_ed25519", []Host{
		{Name: "web", HostName: "127.0.0.1", Port: 22002},
		{Name: "api", HostName: "studio.test", Port: 22001},
	})
	want := `# generated by bh — DO NOT EDIT (rewritten from the environments' settings)

Host bulkhead-api
  HostName studio.test
  Port 22001
  User developer
  IdentityFile "/cfg/id_ed25519"
  StrictHostKeyChecking accept-new
  IdentitiesOnly yes

Host bulkhead-web
  HostName 127.0.0.1
  Port 22002
  User developer
  IdentityFile "/cfg/id_ed25519"
  StrictHostKeyChecking accept-new
  IdentitiesOnly yes
`
	if got != want {
		t.Errorf("fragment:\n%s", got)
	}
}

func TestSyncCreatesEverythingFromNothing(t *testing.T) {
	config := filepath.Join(t.TempDir(), ".ssh", "config")
	if err := Sync(config, "/cfg/key", []Host{{Name: "web", HostName: "127.0.0.1", Port: 22001}}); err != nil {
		t.Fatal(err)
	}
	if got := read(t, config); got != "# >>> bh >>>\nInclude bh/config\n# <<< bh <<<\n" {
		t.Errorf("config:\n%q", got)
	}
	if !strings.Contains(read(t, FragmentPath(config)), "Host bulkhead-web") {
		t.Error("the fragment has no entry for web")
	}
	if included, err := Included(config); err != nil || !included {
		t.Errorf("Included = %v, %v", included, err)
	}
}

func TestEnsureIncludeTouchesOnlyItsBlock(t *testing.T) {
	config := filepath.Join(t.TempDir(), "config")
	// The TypeScript version's block and the user's own entries stay.
	theirs := "# >>> bulkhead >>>\nInclude bulkhead/config\n# <<< bulkhead <<<\n\nHost mine\n  User me\n"
	if err := os.WriteFile(config, []byte(theirs), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := EnsureInclude(config); err != nil {
		t.Fatal(err)
	}
	want := "# >>> bh >>>\nInclude bh/config\n# <<< bh <<<\n\n" + theirs
	if got := read(t, config); got != want {
		t.Errorf("config:\n%q", got)
	}
	// The file's own permissions are kept.
	if info, _ := os.Stat(config); info.Mode().Perm() != 0o644 {
		t.Errorf("mode = %v", info.Mode().Perm())
	}

	// A second run changes nothing; a damaged line inside the block is repaired.
	if err := EnsureInclude(config); err != nil || read(t, config) != want {
		t.Errorf("second run: %v\n%q", err, read(t, config))
	}
	damaged := strings.Replace(want, "Include bh/config", "Include elsewhere", 1)
	os.WriteFile(config, []byte(damaged), 0o644)
	if err := EnsureInclude(config); err != nil || read(t, config) != want {
		t.Errorf("repair: %v\n%q", err, read(t, config))
	}
}

func TestEnsureIncludeFindsItsBlockInACRLFFile(t *testing.T) {
	config := filepath.Join(t.TempDir(), "config")
	crlf := "Host mine\r\n  User me\r\n# >>> bh >>>\r\nInclude bh/config\r\n# <<< bh <<<\r\n"
	os.WriteFile(config, []byte(crlf), 0o600)
	if err := EnsureInclude(config); err != nil {
		t.Fatal(err)
	}
	if got := read(t, config); strings.Count(got, "# >>> bh >>>") != 1 || !strings.Contains(got, "Host mine\r\n") {
		t.Errorf("config:\n%q", got)
	}
}

func TestEnsureIncludeRefusesBrokenMarkers(t *testing.T) {
	for name, text := range map[string]string{
		"begin only": "# >>> bh >>>\nInclude bh/config\n",
		"end only":   "# <<< bh <<<\n",
		"reversed":   "# <<< bh <<<\n# >>> bh >>>\n",
		"twice":      "# >>> bh >>>\n# <<< bh <<<\n# >>> bh >>>\n# <<< bh <<<\n",
	} {
		config := filepath.Join(t.TempDir(), "config")
		os.WriteFile(config, []byte(text), 0o600)
		if err := EnsureInclude(config); err == nil || !strings.Contains(err.Error(), "broken") {
			t.Errorf("%s: err = %v", name, err)
		}
		if read(t, config) != text {
			t.Errorf("%s: the file was changed", name)
		}
	}
}

func TestDefaultPath(t *testing.T) {
	env := func(values map[string]string) func(string) string {
		return func(key string) string { return values[key] }
	}
	if got, _ := DefaultPath("linux", env(map[string]string{"HOME": "/home/me"})); got != filepath.Join("/home/me", ".ssh", "config") {
		t.Errorf("linux: %s", got)
	}
	if got, _ := DefaultPath("windows", env(map[string]string{"USERPROFILE": `C:\Users\me`})); got != filepath.Join(`C:\Users\me`, ".ssh", "config") {
		t.Errorf("windows: %s", got)
	}
	if _, err := DefaultPath("linux", env(nil)); err == nil {
		t.Error("no HOME: no error")
	}
}
