// Package sshconfig keeps the user's ssh client configuration pointing at
// the environments: a file of Host entries that bh owns, and one Include
// line for it in ~/.ssh/config. Nothing else in that file is touched.
package sshconfig

import (
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
)

// The Include line is kept between these markers. The TypeScript version
// used "bulkhead" markers and ~/.ssh/bulkhead/; the two do not share
// anything, so that both can be installed while environments move over.
const (
	beginMark = "# >>> bh >>>"
	endMark   = "# <<< bh <<<"
	// Unquoted and relative: ssh resolves it from ~/.ssh, and so does the
	// host completion of zsh, which cannot strip quotes.
	includeLine = "Include bh/config"
)

// DefaultPath is the user's ssh client configuration.
func DefaultPath(goos string, getenv func(string) string) (string, error) {
	key := "HOME"
	if goos == "windows" {
		key = "USERPROFILE"
	}
	home := getenv(key)
	if home == "" {
		return "", fmt.Errorf("%s is not set", key)
	}
	return filepath.Join(home, ".ssh", "config"), nil
}

// FragmentPath is the file of Host entries, next to the configuration.
func FragmentPath(configPath string) string {
	return filepath.Join(filepath.Dir(configPath), "bh", "config")
}

// KnownHosts is the default known_hosts file, next to the configuration.
func KnownHosts(configPath string) string {
	return filepath.Join(filepath.Dir(configPath), "known_hosts")
}

// Alias is the ssh host name of an environment: `ssh bulkhead-<name>`. It
// is what the TypeScript version used, so editors that remember a remote by
// this name keep finding it.
func Alias(name string) string { return "bulkhead-" + name }

// Host is one environment as the ssh client reaches it.
type Host struct {
	Name     string // the environment's name
	HostName string
	Port     int
}

// Fragment is the contents of the file of Host entries. The terms are the
// ones `bh ssh` uses: the machine key only (an agent full of keys would use
// up the server's tries first), and a host key that is accepted on first
// contact and checked from then on.
func Fragment(identity string, hosts []Host) string {
	hosts = slices.Clone(hosts)
	slices.SortFunc(hosts, func(a, b Host) int { return strings.Compare(a.Name, b.Name) })
	lines := []string{"# generated by bh — DO NOT EDIT (rewritten from the environments' settings)"}
	for _, host := range hosts {
		lines = append(lines,
			"",
			"Host "+Alias(host.Name),
			"  HostName "+host.HostName,
			"  Port "+strconv.Itoa(host.Port),
			"  User developer",
			`  IdentityFile "`+identity+`"`,
			"  StrictHostKeyChecking accept-new",
			"  IdentitiesOnly yes",
		)
	}
	return strings.Join(lines, "\n") + "\n"
}

// EnsureInclude makes sure the configuration includes the fragment: the
// marked block, at the top (ssh takes the first value it finds, so entries
// below a matching Host would lose). A block with a marker missing or
// repeated is left for the user to repair.
func EnsureInclude(configPath string) error {
	existing, err := os.ReadFile(configPath)
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return err
	}
	var lines []string
	if len(existing) > 0 {
		lines = strings.Split(string(existing), "\n")
	}
	begin, end, broken := findBlock(lines)
	if broken {
		return fmt.Errorf("the bh markers in %s are broken; repair or remove the %q block by hand", configPath, beginMark)
	}

	block := []string{beginMark, includeLine, endMark}
	var updated []string
	if begin == -1 {
		updated = append(append(block, ""), lines...)
	} else {
		updated = append(append(slices.Clone(lines[:begin]), block...), lines[end+1:]...)
	}
	text := strings.TrimRight(strings.Join(updated, "\n"), "\n") + "\n"
	if text == string(existing) {
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(configPath), 0o700); err != nil {
		return err
	}
	return writeFile(configPath, text)
}

// findBlock locates the marked block: the lines of its markers, or -1, -1
// when there is none. broken means a marker is missing, repeated or out of
// order.
func findBlock(lines []string) (begin, end int, broken bool) {
	// Markers are looked for without a trailing CR: a file saved with CRLF
	// would otherwise get a second block every time.
	begin, end = -1, -1
	begins, ends := 0, 0
	for i, line := range lines {
		switch strings.TrimSuffix(line, "\r") {
		case beginMark:
			if begins++; begin == -1 {
				begin = i
			}
		case endMark:
			if ends++; end == -1 {
				end = i
			}
		}
	}
	return begin, end, (begin == -1) != (end == -1) || begin > end || begins > 1 || ends > 1
}

// Broken reports whether the configuration has a damaged block, which
// EnsureInclude refuses to touch: until somebody repairs it by hand, the
// Include line is not kept up.
func Broken(configPath string) (bool, error) {
	data, err := os.ReadFile(configPath)
	if errors.Is(err, fs.ErrNotExist) {
		return false, nil
	}
	if err != nil {
		return false, err
	}
	_, _, broken := findBlock(strings.Split(string(data), "\n"))
	return broken, nil
}

// Sync writes the fragment and makes sure it is included. It is called
// whenever the set of environments, a name or a port changes.
func Sync(configPath, identity string, hosts []Host) error {
	fragment := FragmentPath(configPath)
	if err := os.MkdirAll(filepath.Dir(fragment), 0o700); err != nil {
		return err
	}
	if err := writeFile(fragment, Fragment(identity, hosts)); err != nil {
		return err
	}
	return EnsureInclude(configPath)
}

// Included reports whether the configuration has the Include block.
func Included(configPath string) (bool, error) {
	data, err := os.ReadFile(configPath)
	if errors.Is(err, fs.ErrNotExist) {
		return false, nil
	}
	if err != nil {
		return false, err
	}
	lines := strings.Split(strings.ReplaceAll(string(data), "\r\n", "\n"), "\n")
	begin := slices.Index(lines, beginMark)
	return begin != -1 && begin+2 < len(lines) && lines[begin+1] == includeLine && lines[begin+2] == endMark, nil
}

// writeFile replaces a file by renaming a finished copy over it, keeping
// the permissions of an existing file (0600 for a new one).
func writeFile(path, text string) error {
	mode := fs.FileMode(0o600)
	if info, err := os.Stat(path); err == nil {
		mode = info.Mode().Perm()
	}
	temp := path + ".bh-tmp"
	if err := os.WriteFile(temp, []byte(text), mode); err != nil {
		return err
	}
	if err := os.Rename(temp, path); err != nil {
		os.Remove(temp)
		return err
	}
	return nil
}
